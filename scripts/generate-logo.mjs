// Turns scripts/logo-source.png into the comma/sparkle ASCII roundel in lib/logo-ascii.ts.
// Run with: npm run logo
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const COLS = 46; // width of the roundel in characters
const CELL = 0.612; // Space Mono advance width / line height
const SS = 6; // supersampling per cell
const SPARKLES = ["⋆", "₊", "⊹"];

// small deterministic PRNG so the output is stable between runs
let seed = 7;
const rand = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);

const trimmed = await sharp("scripts/logo-source.png")
  .flatten({ background: "#fff" })
  .trim({ threshold: 30 })
  .toBuffer({ resolveWithObject: true });
const ROWS = Math.round((COLS * CELL * trimmed.info.height) / trimmed.info.width);
const { data } = await sharp(trimmed.data)
  .resize(COLS * SS, ROWS * SS, { fit: "fill", kernel: "cubic" })
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

// classify every cell as empty / sun (light tone) / sea (dark tone)
const cells = [];
for (let y = 0; y < ROWS; y++) {
  const row = [];
  for (let x = 0; x < COLS; x++) {
    let white = 0, sun = 0, sea = 0;
    for (let sy = 0; sy < SS; sy++)
      for (let sx = 0; sx < SS; sx++) {
        const i = ((y * SS + sy) * COLS * SS + x * SS + sx) * 3;
        const l = (data[i] + data[i + 1] + data[i + 2]) / 3;
        if (l > 222) white++;
        else if (l > 140) sun++;
        else sea++;
      }
    const n = SS * SS;
    row.push(white / n > 0.42 ? " " : sea >= sun ? "w" : "s");
  }
  cells.push(row);
}
// the sun only lives above the horizon; light pixels below it are anti-aliased wave gaps
const horizon = cells.findIndex((r) => r.includes("w"));
for (let y = horizon; y < ROWS; y++)
  cells[y] = cells[y].map((c) => (c === "s" ? " " : c));

const at = (x, y) => (cells[y] && cells[y][x]) || " ";
const roundel = cells.map((row, y) =>
  row
    .map((c, x) => {
      if (c === " ") return " ";
      if (c === "w") return ",";
      const edge = [at(x - 1, y), at(x + 1, y), at(x, y - 1), at(x, y + 1)].includes(" ");
      if (edge) return ",";
      if ((x + y) % 2) return " ";
      return rand() < 0.3 ? SPARKLES[Math.floor(rand() * 3)] : ",";
    })
    .join("")
);

const width = COLS + 28;
const centre = (s) => {
  const pad = Math.floor((width - [...s].length) / 2);
  return (" ".repeat(pad) + s).padEnd(width + (s.length - [...s].length), " ");
};
const lines = roundel.map(centre);

// a few stray sparkles drifting around the roundel
const put = (y, x, s) => {
  const row = [...lines[y]];
  [...s].forEach((ch, i) => { if (row[x + i] === " ") row[x + i] = ch; });
  lines[y] = row.join("");
};
put(2, 6, "⋆₊");
put(5, width - 9, "⊹");
put(9, 2, "₊");
put(4, width - 14, "₊ ⋆");
put(ROWS - 6, 4, "⊹ ₊");
put(ROWS - 3, width - 10, "⋆₊ ⊹");
put(ROWS - 10, width - 4, "⋆");

await writeFile(
  "lib/logo-ascii.ts",
  `// Generated by scripts/generate-logo.mjs — do not edit by hand.\nexport const LOGO_ROWS: string[] = ${JSON.stringify(lines.map((l) => l.replace(/\s+$/, "")), null, 2)};\nexport const LOGO_COLS = ${width};\n`
);
console.log(lines.join("\n"));
